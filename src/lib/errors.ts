// Maps database/PostgREST errors to Norwegian, user-facing messages.
export function dbErrorToMessage(err: { code?: string; message?: string }): string {
  const message = err.message ?? ''
  if (message.includes('TASK_ARCHIVED')) return 'Oppgaven er arkivert og kan ikke endres.'
  if (message.includes('TASK_COMPLETION_ONLY')) return 'Du kan bare markere dine egne oppgaver som ferdige.'
  if (message.includes('PLANNING_NO_DELETE')) return 'Registreringer kan ikke slettes. Avlys vakten eller arkiver oppgaven.'
  if (message.includes('PLANNING_IMMUTABLE')) return 'Dette feltet kan ikke endres.'
  if (message.includes('PLANNING_NOT_FOUND')) return 'Fant ikke registreringen.'
  if (message.includes('PLANNING_STALE')) return 'Registreringen er endret. Last inn på nytt og kontroller tidspunktene.'
  if (message.includes('PLANNING_PERIOD')) return 'Velg en gyldig periode på høyst 366 dager.'
  if (message.includes('TASK_INVALID_ASSIGNEES')) return 'Velg høyst 20 gyldige personer.'
  if (message.includes('PLANNING_INACTIVE_PERSON')) return 'Velg en aktiv person.'
  if (message.includes('PLANNING_LOCAL_TIME')) return 'Tidspunktet er ugyldig eller tvetydig ved overgang til sommer- eller vintertid. Velg et annet tidspunkt.'
  if (message.includes('PLANNING_WEEK')) return 'Velg en mandag som ukestart.'
  if (message.includes('SHIFT_INTERVAL')) return 'Vakten må slutte etter start, senest neste dag og innen 26 timer.'
  if (message.includes('SHIFT_OVERLAP') || (err.code === '23P01' && message.includes('"work_shifts_no_overlap"'))) return 'Personen har allerede en vakt i dette tidsrommet.'
  if (message.includes('SHIFT_CANCEL_REASON')) return 'Skriv en grunn for avlysningen (minst 3 tegn).'
  if (message.includes('SHIFT_CANCELLED')) return 'Vakten er avlyst og kan ikke endres.'
  if (message.includes('SHIFT_HAS_TIME')) return 'Vakten har registrerte timer. Avlys den og opprett en ny for å bytte person.'
  if (message.includes('TIME_ALREADY_OPEN') || (err.code === '23505' && message.includes('"time_entries_one_open"'))) return 'Du er allerede stemplet inn.'
  if (message.includes('TIME_OVERLAP') || (err.code === '23P01' && message.includes('"time_entries_no_overlap"'))) return 'Tidsrommet overlapper andre registrerte timer.'
  if (message.includes('TIME_INTERVAL')) return 'Slutt må være lik eller etter start, og tidspunktene kan ikke være i fremtiden.'
  if (message.includes('TIME_REASON')) return 'Skriv en grunn for korrigeringen (minst 3 tegn).'
  if (message.includes('TIME_RATE')) return 'Bare en manglende timesats kan fylles inn. Sett gjeldende sats på Brukere først.'
  if (message.includes('RATE_INVALID')) return 'Skriv timesatsen i kroner, fra 0 til 10 000, med høyst to desimaler.'
  if (message.includes('TAKINGS_FUTURE_DAY')) return 'Markedsdagen har ikke vært ennå.'
  if (message.includes('TAKINGS_CANCELLED_DAY')) return 'Markedsdagen er avlyst.'
  if (message.includes('TAKINGS_EMPTY')) return 'Fyll inn minst ett beløp.'
  if (message.includes('RECEIPT_PARENT_INVALID')) return 'Du kan bare legge kvittering på dine egne poster.'
  if (message.includes('LEDGER_NO_DELETE')) return 'Poster og kvitteringer kan ikke slettes. Annuller i stedet.'
  if (message.includes('LEDGER_IMMUTABLE')) return 'Dette feltet kan ikke endres.'
  if (message.includes('LEDGER_VOIDED')) return 'Posten er annullert og kan ikke endres.'
  if (message.includes('LEDGER_FUTURE_DATE')) return 'Datoen kan ikke være i fremtiden.'
  if (message.includes('LEDGER_CATEGORY_MISMATCH')) return 'Kategorien passer ikke til typen post.'
  if (message.includes('LEDGER_CATEGORY_INACTIVE')) return 'Kategorien er ikke i bruk lenger.'
  if (message.includes('LEDGER_INCOME_VIA_TAKINGS')) return 'Inntekt fra marked registreres som dagsoppgjør.'
  if (message.includes('LEDGER_VOID_REASON')) return 'Skriv en grunn for annulleringen.'
  if (message.includes('LEDGER_CATEGORY_SYSTEM')) return 'Denne kategorien brukes av dagsoppgjør og kan ikke skrus av.'
  if (message.includes('LEDGER_SETTLE_INVALID')) return 'Bare ubetalte regninger og utlegg kan markeres som oppgjort.'
  if (message.includes('SORTING_CHECK_MISSING')) return 'Partiet må sorteringskontrolleres før pakking.'
  if (message.includes('NOT_ENOUGH_LEFT')) return 'Det er ikke nok igjen av partiet.'
  if (message.includes('STOCK_NEGATIVE')) return 'Det er ikke nok på lager.'
  if (message.includes('WEIGHT_BELOW_USED')) return 'Vekten kan ikke være mindre enn det som allerede er pakket eller kastet.'
  if (message.includes('FUTURE_TIME')) return 'Tidspunktet kan ikke være i fremtiden.'
  if (err.code === '42501') return 'Du har ikke tilgang til dette.'
  if (err.code === '23505') return 'Dette finnes allerede.'
  return 'Noe gikk galt. Prøv igjen.'
}
