import { test, expect } from '@playwright/test'
import ExcelJS from 'exceljs'
import { planningUser, loginPlanning, checked, planningClosedEntry, closePlanningClock } from './planning-helpers'
test.use({ viewport: { width: 390, height: 844 } })
for (const role of ['picker','seller'] as const) test(`${role} own weekly/monthly hours, private snapshot pay and protected export`, async ({ page }) => {
 const owner=await planningUser('owner'), person=await planningUser(role), other=await planningUser('picker')
 checked(await owner.client.from('work_rates').upsert({profile_id:person.id,hourly_rate_ore:25000},{onConflict:'profile_id'}))
 const matchingShift=crypto.randomUUID()
 checked(await owner.client.from('work_shifts').insert({id:matchingShift,profile_id:person.id,starts_at:new Date(Date.now()-3600000).toISOString(),ends_at:new Date(Date.now()+3600000).toISOString(),kind:'other',note:'E2E hours cancelled matching shift'}))
 const entry=await planningClosedEntry(owner,person,'2026-03-31T21:30:00Z','2026-03-31T22:30:00Z')
 checked(await owner.client.from('work_rates').upsert({profile_id:person.id,hourly_rate_ore:30000},{onConflict:'profile_id'}))
 expect(entry.shift_id).toBe(matchingShift)
 checked(await owner.client.rpc('cancel_work_shift',{p_id:matchingShift,p_reason:'E2E cancellation retains actual pay'}))
 const plannedShift=crypto.randomUUID()
 checked(await owner.client.from('work_shifts').insert({id:plannedShift,profile_id:person.id,starts_at:'2026-03-31T08:00:00Z',ends_at:'2026-03-31T10:00:00Z',kind:'packing'}))
 await planningClosedEntry(owner,other,'2026-03-31T08:00:00Z','2026-03-31T09:00:00Z')
 await loginPlanning(page,person.email)
 await page.goto('/admin/timer?mode=month&month=2026-03')
 await expect(page.getByRole('heading',{name:'Timer',exact:true})).toBeVisible()
 await expect(page.getByTestId('worked-amount')).toHaveText('125,00 kr')
 await expect(page.getByTestId('planned-amount')).toHaveText('600,00 kr')
 await expect(page.getByText('Timesats: 300,00 kr/time')).toBeVisible()
 await expect(page.getByText(other.label)).toHaveCount(0)
 await page.getByRole('link',{name:'Vis registrering'}).click(); await expect(page).toHaveURL(new RegExp(entry.id))
 await page.goto('/admin/timer?mode=week&week=2026-03-30'); await expect(page.getByTestId('worked-amount')).toHaveText('250,00 kr')
 await page.goto('/admin/timer?mode=month&month=2026-04'); await expect(page.getByTestId('worked-amount')).toHaveText('125,00 kr')
 expect((await page.goto('/admin/timer/eksport'))?.status()).toBe(404)
 expect((await page.request.get('/api/planlegging/export.xlsx?month=2026-03')).status()).toBe(404)
 checked(await owner.client.rpc('cancel_work_shift',{p_id:plannedShift,p_reason:'E2E hours cleanup'}))
})
test('owner inactive history, missing/open preview, exact workbook totals and empty month', async ({ page }) => {
 test.setTimeout(60000)
 const owner=await planningUser('owner'), person=await planningUser('picker'), missing=await planningUser('seller'), zero=await planningUser('picker')
 try {
 checked(await owner.client.from('work_rates').upsert({profile_id:person.id,hourly_rate_ore:10000},{onConflict:'profile_id'}))
 await planningClosedEntry(owner,person,'2026-02-03T09:00:00Z','2026-02-03T09:01:00Z')
 await planningClosedEntry(owner,person,'2026-02-03T10:00:00Z','2026-02-03T10:01:00Z')
 await planningClosedEntry(owner,missing,'2026-02-03T09:00:00Z','2026-02-03T10:00:00Z')
 checked(await owner.client.from('work_rates').upsert({profile_id:zero.id,hourly_rate_ore:0},{onConflict:'profile_id'}))
 await planningClosedEntry(owner,zero,'2026-02-03T09:00:00Z','2026-02-03T10:00:00Z')
 const open=checked(await owner.client.rpc('clock_in',{p_start_key:crypto.randomUUID()})).data!
 checked(await owner.client.rpc('correct_time_entry',{p_id:open.id,p_started_at:'2026-01-01T00:00:00Z',p_ended_at:null,p_reason:'E2E forgotten',p_expected_version:open.version}))
 checked(await owner.client.from('profiles').update({active:false}).eq('id',person.id))
 await loginPlanning(page,owner.email)
 await page.goto('/admin/timer?mode=month&month=2026-02')
 await expect(page.getByRole('heading',{name:`${person.label} (inaktiv)`,exact:true})).toBeVisible()
 await page.getByLabel('Person').selectOption(person.id)
 await page.getByRole('button',{name:'Vis',exact:true}).click()
 await expect(page.getByTestId('worked-amount')).toHaveText('3,34 kr')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.goto('/admin/timer/eksport?month=2026-02')
 await expect(page.getByText('Ufullstendig grunnlag')).toBeVisible()
 await expect(page.getByText('Glemt å stemple ut?',{exact:false}).first()).toBeVisible()
 const response=await page.request.get('/api/planlegging/export.xlsx?month=2026-02'); expect(response.status()).toBe(200)
 const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(await response.body() as unknown as ArrayBuffer)
 const rows=workbook.getWorksheet('Timer')!.getSheetValues().slice(2) as unknown[][]
 const own=rows.filter(row=>row[1]===person.label)
 expect(own).toHaveLength(2);expect(own.reduce((sum,row)=>sum+Math.round(Number(row[5])*100),0)).toBe(334)
 expect(rows.find(row=>row[1]===missing.label)?.[5]).toBeUndefined()
 expect(rows.find(row=>row[1]===zero.label)?.[5]).toBe(0)
 const total=rows.reduce((sum,row)=>sum+(typeof row[5]==='number'?Math.round(row[5]*100):0),0)
 await expect(page.getByTestId('export-amount')).toHaveText((total/100).toLocaleString('nb-NO',{minimumFractionDigits:2,maximumFractionDigits:2})+' kr')
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'Last ned Excel'}).click();expect((await download).suggestedFilename()).toBe('ramslok-timer-2026-02.xlsx')
 const empty=await page.request.get('/api/planlegging/export.xlsx?month=2001-01');const emptyBook=new ExcelJS.Workbook();await emptyBook.xlsx.load(await empty.body() as unknown as ArrayBuffer);expect(emptyBook.getWorksheet('Timer')!.rowCount).toBe(1)
 } finally { await closePlanningClock(owner) }
})
